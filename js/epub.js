/* ============================================================
 * epub.js — EPUB 3 组装（OPF / NAV / NCX / XHTML / CSS）
 * 封面页、目录页与正文一样按「章节」处理，统一参与 nav 与 spine 排序
 * 同时输出 NCX 以兼容老阅读器
 * ============================================================ */
(function (global) {
  'use strict';

  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function pad(n) { return n < 10 ? '0' + n : '' + n; }

  function isoNow() {
    var d = new Date();
    return d.getUTCFullYear() + '-' + pad(d.getUTCMonth() + 1) + '-' + pad(d.getUTCDate()) +
      'T' + pad(d.getUTCHours()) + ':' + pad(d.getUTCMinutes()) + ':' + pad(d.getUTCSeconds()) + 'Z';
  }

  function makeId(seed) {
    var h = 0x811c9dc5;
    for (var i = 0; i < seed.length; i++) {
      h ^= seed.charCodeAt(i);
      h = (h * 0x01000193) >>> 0;
    }
    var s = h.toString(16).padStart(8, '0');
    for (var k = 0; k < 4; k++) s += Math.floor(Math.random() * 0xffffffff).toString(16).padStart(8, '0');
    return 'urn:uuid:' + s.slice(0, 8) + '-' + s.slice(8, 12) + '-4' + s.slice(13, 16) +
      '-a' + s.slice(17, 20) + '-' + s.slice(20, 32);
  }

  /* ---------- 默认样式表 ---------- */
  function buildCSS(opt) {
    var fs = opt.fontSize || 100;      // %
    var lh = opt.lineHeight || 150;    // %
    var mt = opt.marginTop != null ? opt.marginTop : 0;
    var mb = opt.marginBottom != null ? opt.marginBottom : 0;
    var ml = opt.marginLeft != null ? opt.marginLeft : 0;
    var mr = opt.marginRight != null ? opt.marginRight : 0;
    var indent = opt.indentEm != null ? opt.indentEm : 2;
    var align = opt.textAlign || 'justify';
    var pmt = opt.paraMargin != null ? opt.paraMargin : 0.35;

    return [
      '/* Generated by EasyPub Web */',
      '@page { margin: ' + mt + 'px ' + mr + 'px ' + mb + 'px ' + ml + 'px; }',
      'html, body { margin:0; padding:0; }',
      'body {',
      '  font-size: ' + fs + '%;',
      '  line-height: ' + lh + '%;',
      '  text-align: ' + align + ';',
      '  orphans: 0; widows: 0;',
      '}',
      'p {',
      '  margin: ' + pmt + 'em 0 ' + pmt + 'em 0;',
      '  padding-right: 0.5em;',      /* 给行尾悬挂标点（引号/句号）留出溢出空间，避免撑破容器 */
      '  text-indent: 0;',
      '  orphans: 0; widows: 0;',
      '  word-wrap: break-word;',      /* 旧浏览器兜底，务必在前 */
      '  overflow-wrap: anywhere;',    /* 现代浏览器：可在任意字符间断行 */
      '  word-break: break-word;',
      '}',
      'p.a { text-indent: ' + indent + 'em; }',
      'h1, h2, h3, h4 { text-align: center; font-weight: normal; page-break-after: avoid; word-wrap: break-word; overflow-wrap: anywhere; }',
      'h2.titlel1std { font-size: 1.7em; margin: 35% 0 0 0; page-break-before: always; }',
      'h2.titlel2std { font-size: 1.35em; margin: 1.6em 0 1.2em 0; }',
      'h3.titlel3std { font-size: 1.15em; margin: 1.2em 0 0.8em 0; }',
      'div.centeredimage { text-align:center; margin: 0.8em 0; }',
      'div.centeredimage img { max-width: 100%; }',
      'img { max-width: 100%; }',
      '/* 目录页 */',
      'nav ol { list-style: none; padding-left: 0; margin: 0; }',
      'nav ol ol { padding-left: 1.2em; }',
      'nav li { margin: 0.45em 0; line-height: 1.45; }',
      'nav a { text-decoration: none; color: #000; }',
      '.tocpage a { text-decoration: none; color: #000; }',
      '.tocpage p { text-indent: 0; margin: 0.4em 0; }',
      '.tocpage .lv1 { font-size: 1.15em; font-weight: bold; margin-top: 1.1em; }',
      '.tocpage .lv2 { padding-left: 1.4em; }',
      '.tocpage .lv3 { padding-left: 2.8em; font-size: 0.95em; }',
      '.tocpage .lv4 { padding-left: 4.2em; font-size: 0.95em; }',
      '.coverpage { margin:0; padding:0; text-align:center; }',
      '.booktitle { margin-top: 32%; font-size: 2.4em; text-align: center; text-indent: 0; }',
      '.bookauthor { margin-top: 1.2em; font-size: 1.2em; text-align: center; text-indent: 0; }'
    ].join('\n');
  }

  /* ---------- 层级树 ---------- */
  function buildTree(items) {
    var root = { item: null, children: [] };
    var stack = [{ level: 0, node: root }];
    for (var i = 0; i < items.length; i++) {
      var it = items[i];
      var node = { item: it, children: [] };
      while (stack.length > 1 && stack[stack.length - 1].level >= it.level) stack.pop();
      stack[stack.length - 1].node.children.push(node);
      stack.push({ level: it.level, node: node });
    }
    return root.children;
  }

  function navList(nodes) {
    if (!nodes.length) return '';
    var s = '<ol>\n';
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i];
      s += '<li><a href="' + n.item.href + '">' + esc(n.item.title) + '</a>';
      if (n.children.length) s += '\n' + navList(n.children);
      s += '</li>\n';
    }
    return s + '</ol>\n';
  }

  function ncxPoints(nodes, counter) {
    var s = '';
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i];
      var order = ++counter.n;
      s += '<navPoint id="np' + order + '" playOrder="' + order + '">' +
        '<navLabel><text>' + esc(n.item.title) + '</text></navLabel>' +
        '<content src="' + n.item.href + '"/>';
      if (n.children.length) s += ncxPoints(n.children, counter);
      s += '</navPoint>\n';
    }
    return s;
  }

  function xhtmlShell(title, body, lang, isChapter) {
    var href = isChapter ? '../style.css' : 'style.css';
    return '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE html>\n' +
      '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="' + esc(lang) + '">\n' +
      '<head><meta charset="utf-8"/><title>' + esc(title) + '</title>' +
      '<link rel="stylesheet" type="text/css" href="' + href + '"/></head>\n' +
      '<body>\n' + body + '\n</body></html>';
  }

  /**
   * 组装并输出 EPUB
   * @param {object} o {
   *   meta,
   *   chapters: [{ type:'cover'|'toc'|'text', title, level, html }],   // 顺序即 spine 顺序
   *   cover: { bytes, mime, width, height },   // 封面图数据（type:'cover' 的章节使用）
   *   css, cssOpt
   * }
   */
  function buildEPUB(o) {
    var meta = o.meta || {};
    var chapters = (o.chapters || []).slice();
    var zip = new global.EasyZip.ZipWriter();
    var manifest = [];
    var spine = [];
    var title = meta.title || '未命名';
    var lang = meta.language || 'zh-CN';
    var uuid = makeId(title + (meta.author || '') + Date.now());

    var hasCoverImg = !!(o.cover && o.cover.bytes && o.cover.bytes.length);

    /* --- 分配资源路径 --- */
    var textSeq = 0;
    chapters.forEach(function (c) {
      if (c.type === 'cover') c.href = 'cover.xhtml';
      else if (c.type === 'toc') c.href = 'tocpage.xhtml';
      else c.href = 'text/chapter' + (textSeq++) + '.xhtml';
      if (!c.level) c.level = c.type === 'text' ? 2 : 1;
    });

    /* 可见目录页只列正文类章节，不列封面页和目录页自身 */
    var tocEntries = chapters.filter(function (c) { return c.type === 'text'; });

    var tree = buildTree(chapters);

    /* --- mimetype 必须首个且不压缩 --- */
    var tasks = [zip.add('mimetype', 'application/epub+zip', { store: true })];

    tasks.push(zip.add('META-INF/container.xml',
      '<?xml version="1.0" encoding="UTF-8"?>\n' +
      '<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">\n' +
      '<rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles>\n' +
      '</container>'));

    /* --- 样式 --- */
    var css = o.css || buildCSS(o.cssOpt || {});
    tasks.push(zip.add('OEBPS/style.css', css));
    manifest.push('<item id="css" href="style.css" media-type="text/css"/>');

    /* --- 封面图片资源（仅当存在封面章节时写入） --- */
    var needCoverImg = hasCoverImg && chapters.some(function (c) { return c.type === 'cover'; });
    var coverExt = '', coverMime = '';
    if (needCoverImg) {
      coverExt = /png/i.test(o.cover.mime) ? 'png' : 'jpg';
      coverMime = /png/i.test(o.cover.mime) ? 'image/png' : 'image/jpeg';
      tasks.push(zip.add('OEBPS/images/cover.' + coverExt, o.cover.bytes));
      manifest.push('<item id="cover-image" href="images/cover.' + coverExt + '" media-type="' + coverMime + '" properties="cover-image"/>');
    }

    /* --- 逐章生成 --- */
    chapters.forEach(function (c) {
      if (c.type === 'cover') {
        var vw = (o.cover && o.cover.width) || 600;
        var vh = (o.cover && o.cover.height) || 800;
        var body;
        if (needCoverImg) {
          body = '<div class="coverpage">' +
            '<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" ' +
            'version="1.1" width="100%" height="100%" viewBox="0 0 ' + vw + ' ' + vh + '" preserveAspectRatio="xMidYMid meet">' +
            '<image width="' + vw + '" height="' + vh + '" xlink:href="images/cover.' + coverExt + '"/></svg>' +
            '</div>';
        } else {
          body = '<p class="booktitle">' + esc(title) + '</p>' +
            (meta.author ? '<p class="bookauthor">' + esc(meta.author) + '</p>' : '');
        }
        tasks.push(zip.add('OEBPS/' + c.href, xhtmlShell(c.title, body, lang, false)));
      } else if (c.type === 'toc') {
        var tocHtml = '<h1 style="text-align:center;font-weight:normal;font-size:1.5em;">' + esc(c.title) + '</h1>\n';
        tocHtml += '<div class="tocpage">\n';
        tocEntries.forEach(function (t) {
          var lv = Math.min(Math.max(t.level || 2, 1), 4);
          tocHtml += '<p class="lv' + lv + '"><a href="' + t.href + '">' + esc(t.title) + '</a></p>\n';
        });
        tocHtml += '</div>\n';
        tasks.push(zip.add('OEBPS/' + c.href, xhtmlShell(c.title, tocHtml, lang, false)));
      } else {
        var lv = Math.min(Math.max(c.level || 2, 1), 3);
        var tag = lv === 1 ? 'h2' : (lv === 2 ? 'h2' : 'h3');
        var cls = lv === 1 ? 'titlel1std' : (lv === 2 ? 'titlel2std' : 'titlel3std');
        var b = '<' + tag + ' class="' + cls + '" id="ttl">' + esc(c.title) + '</' + tag + '>\n' + (c.html || '');
        tasks.push(zip.add('OEBPS/' + c.href, xhtmlShell(c.title, b, lang, true)));
      }
      manifest.push('<item id="' + itemIdOf(c) + '" href="' + c.href + '" media-type="application/xhtml+xml"/>');
      spine.push('<itemref idref="' + itemIdOf(c) + '"/>');
    });

    function itemIdOf(c) {
      if (c.type === 'cover') return 'cover';
      if (c.type === 'toc') return 'tocpage';
      return 'c' + c.href.replace(/\D/g, '');
    }

    /* --- NAV (EPUB3)：包含封面、目录、正文全部条目 --- */
    var navBody = '<nav epub:type="toc" id="toc">\n' +
      '<h1 style="text-align:center;font-weight:normal;font-size:1.5em;">目录</h1>\n' +
      navList(tree) + '</nav>\n';
    tasks.push(zip.add('OEBPS/nav.xhtml',
      '<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE html>\n' +
      '<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="' + esc(lang) + '">\n' +
      '<head><meta charset="utf-8"/><title>目录</title><link rel="stylesheet" type="text/css" href="style.css"/></head>\n' +
      '<body>\n' + navBody + '</body></html>'));
    manifest.push('<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>');

    /* --- NCX (EPUB2 兼容) --- */
    var counter = { n: 0 };
    tasks.push(zip.add('OEBPS/toc.ncx',
      '<?xml version="1.0" encoding="utf-8"?>\n' +
      '<ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1" xml:lang="' + esc(lang) + '">\n' +
      '<head><meta name="dtb:uid" content="' + esc(uuid) + '"/>' +
      '<meta name="dtb:depth" content="4"/><meta name="dtb:totalPageCount" content="0"/>' +
      '<meta name="dtb:maxPageNumber" content="0"/></head>\n' +
      '<docTitle><text>' + esc(title) + '</text></docTitle>\n' +
      '<navMap>\n' + ncxPoints(tree, counter) + '</navMap>\n</ncx>'));
    manifest.push('<item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>');

    /* --- OPF --- */
    var metaXml = [
      '<dc:identifier id="bookid">' + esc(meta.isbn || uuid) + '</dc:identifier>',
      '<dc:title>' + esc(title) + '</dc:title>'
    ];
    if (meta.author) metaXml.push('<dc:creator id="creator">' + esc(meta.author) + '</dc:creator>');
    if (meta.publisher) metaXml.push('<dc:publisher>' + esc(meta.publisher) + '</dc:publisher>');
    metaXml.push('<dc:language>' + esc(lang) + '</dc:language>');
    if (meta.date) metaXml.push('<dc:date>' + esc(meta.date) + '</dc:date>');
    if (meta.subject) metaXml.push('<dc:subject>' + esc(meta.subject) + '</dc:subject>');
    if (meta.description) metaXml.push('<dc:description>' + esc(meta.description) + '</dc:description>');
    metaXml.push('<dc:rights>Created with EasyPub Web</dc:rights>');
    metaXml.push('<meta property="dcterms:modified">' + isoNow() + '</meta>');
    if (needCoverImg) metaXml.push('<meta name="cover" content="cover-image"/>');

    var opf = '<?xml version="1.0" encoding="utf-8"?>\n' +
      '<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="bookid" xml:lang="' + esc(lang) + '">\n' +
      '<metadata xmlns:dc="http://purl.org/dc/elements/1.1/">\n' + metaXml.join('\n') + '\n</metadata>\n' +
      '<manifest>\n' + manifest.join('\n') + '\n</manifest>\n' +
      '<spine toc="ncx">\n' + spine.join('\n') + '\n</spine>\n' +
      '</package>';

    tasks.push(zip.add('OEBPS/content.opf', opf));

    return Promise.all(tasks).then(function () {
      return zip.generate();
    });
  }

  global.EasyEpub = {
    buildEPUB: buildEPUB,
    buildCSS: buildCSS,
    escape: esc
  };
})(typeof self !== 'undefined' ? self : this);
